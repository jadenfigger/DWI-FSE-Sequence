def int_timer_arguments(text):
    """Pass int waittimer arguments in the method shot.

    waittimer(int) receives the low 16 bits of a long argument and PPLC emits
    W008 for every such call; with v18's 11 inherited W007/W008 the method shot
    exceeded the 20-message abort limit. Each long argument is assigned to an
    int once setup has validated it (assignment truncates to the same low 16
    bits without a warning); constant arguments become int literals. Arguments
    are evaluated before the wait, so event times are unchanged and the timed
    windows only gain slack.
    """
    longs = set()
    for declaration in re.findall(r'\blong ([^;]+);', DECL_COMMON + DECL_SSMGOT):
        longs.update(re.match(r'\w+', v.strip())[0] for v in declaration.split(','))
    # The only timer argument changed inside the train becomes an int itself.
    longs.discard('v19_wait_next')
    consts = {k: int(v) for k, v in re.findall(r'^#define (V19_\w+) (\d+)L$', MACROS, re.M)}
    begin, end = text.index('\nv19_mat_window:\n'), text.index('\nv19_exit:\n')
    shot = text[begin:end]
    names = {}

    def int_argument(arg):
        words = set(re.findall(r'\b[A-Za-z_]\w*', arg))
        if not words & longs:
            if not words & set(consts) and not re.search(r'\d+L\b', arg):
                return arg
            value = re.sub(r'\bV19_\w+\b', lambda w: str(consts[w[0]]), arg)
            assert re.fullmatch(r'[\dL\s+*()-]+', value), arg
            value = eval(value.replace('L', ''))
            assert 0 <= value <= 32767, arg
            return str(value)
        assert words <= longs | set(consts), arg
        key = arg.replace(' ', '')
        if key not in names:
            name = key
            for old, new in TIMER_NAMES:
                name = name.replace(old, new)
            name = 'v19_i_' + re.sub('_+', '_', name).strip('_')
            assert len(name) <= 31 and not re.search(r'\b' + name + r'\b', text, re.I), name
            names[key] = name
        return names[key]

    out, pos = [], 0
    for m in re.finditer(r'\bwaittimer\(', shot):
        close = _call_end(shot, m.end() - 1)
        out.append(shot[pos:m.end()] + int_argument(shot[m.end():close - 1]) + ')')
        pos = close
    shot = ''.join(out) + shot[pos:]
    shot = re.sub(r'\bv19_wait_next = ([^;]+);',
                  lambda m: 'v19_wait_next = ' + int_argument(m[1].strip()) + ';', shot)
    text = text[:begin] + shot + text[end:]
    setup = text.index(TIMER_SETUP_ANCHOR)
    for key in names:
        for word in set(re.findall(r'v19_\w+', key)):
            later = [m.start() for m in re.finditer(r'\b' + word + r'\s*=(?!=)', text)]
            assert later and max(later) < setup, word
    text = re.sub(r'(\blong [^;]*?)\bv19_wait_next, ', r'\1', text, count=1)
    ints = ['v19_wait_next'] + list(names.values())
    decl = ''.join('\tint ' + ', '.join(ints[i:i + 6]) + ';\n' for i in range(0, len(ints), 6))
    assert text.count(TIMER_DECL_ANCHOR) == 1 and text.count(TIMER_SETUP_ANCHOR) == 1
    text = text.replace(TIMER_DECL_ANCHOR, TIMER_DECL_ANCHOR + decl)
    assign = ''.join(f'\t\t{name} = {key};\n' for key, name in names.items())
    return text.replace(TIMER_SETUP_ANCHOR, assign + TIMER_SETUP_ANCHOR)


def anchor_insert(text, anchor, insertion, *, before=False, occurrence=None):
    count = text.count(anchor)
    if count != 1 and occurrence is None:
        raise SystemExit(f"anchor not unique ({count}): {anchor!r}")
    idx = text.find(anchor) if occurrence is None else [i for i in range(len(text)) if text.startswith(anchor, i)][occurrence]
    pos = idx if before else idx + len(anchor)
    return text[:pos] + compiler_compatible(insertion) + text[pos:]



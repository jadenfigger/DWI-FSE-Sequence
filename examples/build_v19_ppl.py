CONTROL_PPR = ROOT / "experiments/FSE-DWI_10-05-2026_v18_test1e/FSE-DWI_10-05-2026_v18_test1.ppr"
# Disclosed approximations (docs/v19/README.md): Alsop 1997 p530 first five
# angles completed at 60 deg. Gibbons' Busse schedule is unpublished; with the
# centric eight-echo control (k-space centre at echo 1) the ss-MGOT adaptation
# uses the same stabilised ramp (minimum 60 >= the published 55 deg minimum) so
# the two adaptations differ only in their preparation mechanism.
# Train crusher: 3x the test1e value (-8223 DAC) because the PPL requires
# |C| >= 3|D| (Bloch-event audit: |C|~|D| leaves RF FIDs unspoiled).
METHOD_CRUSH_AMP = -8223
FLIPS = {
    "alsop": [1422, 949, 692, 630, 602, 600, 600, 600],
    "ssmgot": [1422, 949, 692, 630, 602, 600, 600, 600],
}


def ppr_array(name, values, n=64):
    vals = list(values) + [values[-1]] * (n - len(values))
    out = f":VAR_ARRAY {name}, {n}, {vals[0]}\r\n"
    rest = vals[1:]
    for i in range(0, len(rest), 8):
        out += ", " + ", ".join(str(v) for v in rest[i:i + 8]) + "\r\n"
    return out


def build_ppr(method, ppl_name, flips=None):
    text = CONTROL_PPR.read_bytes().decode("latin-1")
    lines = text.split("\r\n")
    assert lines[0].startswith(":PPL ")
    lines[0] = f":PPL {ppl_name}"
    text = "\r\n".join(lines)
    assert text.count(":VAR crush_amp, -2741\r\n") == 1
    text = text.replace(":VAR crush_amp, -2741\r\n", f":VAR crush_amp, {METHOD_CRUSH_AMP}\r\n")
    v = ":VAR v19_on, 1\r\n:VAR v19_cycles, 2\r\n:VAR v19_comp_flat, 1000\r\n"
    v += ppr_array("v19_flip_tenths", flips or FLIPS[method])
    if method == "ssmgot":
        v += (":VAR v19_slab_pml, 3000\r\n:VAR v19_tip_pml, 1667\r\n"
              ":VAR v19_spoil_cpmm, 32\r\n:VAR v19_spoil_dac, 16384\r\n")
    anchor = ":DSP_ROUTINE"
    assert text.count(anchor) == 1
    text = text.replace(anchor, v + anchor)
    # Method-only tables hold MAX_DIFF_ACQ rows; entries beyond no_diff_acq are unused.
    assert int(re.search(r":VAR no_diff_acq, (\d+)\r\n", text).group(1)) <= MAX_DIFF_ACQ
    for name in ("acq_b", "acq_grad", "acq_x", "acq_y", "acq_z"):
        m = re.search(r":VAR_ARRAY " + name + r", 512, ([^\r]*)\r\n((?:,[^\r]*\r\n)*)", text)
        values = [int(x) for x in (m.group(1) + m.group(2)).replace("\r\n", "").split(",") if x.strip()]
        assert len(values) == 512, name
        text = text[:m.start()] + ppr_array(name, values[:MAX_DIFF_ACQ], MAX_DIFF_ACQ) + text[m.end():]
    return text


def main_ppr():
    hashes = {}
    for method, path in OUT.items():
        ppr = path.with_suffix(".ppr")
        ppr.write_bytes(build_ppr(method, path.name).encode("latin-1"))
        hashes[ppr.name] = hashlib.sha256(ppr.read_bytes()).hexdigest()
    print(json.dumps(hashes, indent=1))


if __name__ == "__main__":
    main()
    main_ppr()

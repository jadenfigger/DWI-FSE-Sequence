MACROS = r'''
// [V19-MACROS] Method timing primitives. Times in 0.1-us ticks are long.
// V19_TAIL_US: tail window for SetList/SelectMatrix/phase() (phase ~29 us,
// EVO manual 3.3.1.11). V19_GAP_MIN: minimum delay32 gap. V19_ANCHOR: estimated
// statement-transition cost between a waittimer/delay32 exit and the next
// starttimer entry (0.5 us = documented starttimer duration, manual 4.6; the
// true value needs a compiler/console trace). V19_INIT_COST: initiate() 7.6 us
// (manual 3.3.2 table).
#define V19_TAIL_US 100L
#define V19_GAP_MIN 20L
#define V19_ANCHOR 5L
#define V19_INIT_COST 76L
// Timer counts 0..49999 (5 ms): every waittimer must be ISSUED and TARGETED
// below ~4.9 ms after its starttimer (manual p90; v18 uses <= 47975 ticks).
#define V19_MAX_WAIT 49000L
// Post-initiate calculation window: same budget as v18 (8997 ticks; v18
// comment measures 8236). Holds CREATE_MATRIX + three long divisions.
#define V19_ADC_SLOW 8997L
// Pad after rfon(0)+PDD mask before re-anchoring (ticks); covers ~10 statements.
#define V19_POST_RF 200L
// Real-RF calibration: board multiplier = scale(rfcal, numerator, 10000)
// (inferred linear DAC x multiplier model, docs/v19/rf_library_manifest.json)
#define V19_SELECTOR(dest, tbw100, t_us, pml) templ1 = IntToLong(v19_gabs)*IntToLong(tbw100);\
templ1 = ((templ1*100L)/IntToLong(t_us))*10L;\
templ1 = (templ1*1000L+535L)/1070L;\
templ1 = (templ1*10L+IntToLong(pml)/2L)/IntToLong(pml);\
if ((templ1<1L)||(templ1>IntToLong(crusher_max_dac))||(templ1*100L>IntToLong(crusher_slew_dac_100us)*IntToLong(tramp))) {\
printf("V19 selector DAC %ld outside amplitude/slew ceiling\n", templ1); goto end; }\
dest = templ1*IntToLong(v19_gsign);
// Compensation lobe NEGPULSE_SEC(v19_comp_flat): area -sec*(flat+tramp) exactly
// (library ramps 0_mn_sec/mn_0_sec each 0.5*tramp). Target area after/before the
// RF = -(kappa*T + pad/2 + ramp_area_fraction*tramp) * selector.
#define V19_COMP(dest, g, k10000, t_us, pad_us, ramp10000) templ2 = (IntToLong(k10000)*IntToLong(t_us)+5000L)/10000L + IntToLong(pad_us)/2L + (IntToLong(ramp10000)*IntToLong(tramp)+5000L)/10000L;\
templ1 = IntToLong(g);\
if (templ1<0L) templ1 = -templ1;\
templ1 = (templ1*templ2 + IntToLong(v19_comp_flat+tramp)/2L)/IntToLong(v19_comp_flat+tramp);\
if ((templ1<1L)||(templ1>IntToLong(crusher_max_dac))||(templ1*100L>IntToLong(crusher_slew_dac_100us)*IntToLong(tramp))) {\
printf("V19 compensation DAC %ld outside amplitude/slew ceiling\n", templ1); goto end; }\
dest = templ1*IntToLong(v19_gsign);
#define V19_RFMUL(dest, num) dest = scale(rfcal, num, 10000);\
if ((dest<1)||(dest>2047)) { printf("V19 RF multiplier outside 1..2047\n"); goto end; }
// RF block plateau: RF + 2*rfdelay, rounded up to tramp/10 (v18 crush_rf_flat rule).
#define V19_FLAT(dest, rfn) temp = tramp/10;\
dest = ((rf_length[rfn]+2*rfdelay+temp-1)/temp)*temp;\
if (dest%2!=0) dest = dest+temp;
// RF block window ticks relative to the list start. RF centre = plateau centre
// + rfdelay (the v18-documented gradient group-delay compensation).
// go/off: RF start / gate-off relative to the list start; offl: gate-off
// relative to the pre-RF re-anchor (go-lead). rem: from the post-RF re-anchor
// to list end + 20 us. Every waittimer is issued/targeted < V19_MAX_WAIT.
#define V19_RFTIMES(go, off, offl, rem, blk, pre_us, flat, rfn, list_us) go = (pre_us + v19_r + IntToLong(flat-rf_length[rfn])/2L + v19_rd)*10L;\
off = go + IntToLong(rf_length[rfn])*10L + 50L;\
offl = v19_lead - V19_ANCHOR + IntToLong(rf_length[rfn])*10L + 50L;\
rem = (list_us + 20L)*10L - off - V19_POST_RF - V19_ANCHOR;\
blk = list_us + 20L + V19_TAIL_US;\
if ((go-v19_lead<300L)||(go-v19_lead>V19_MAX_WAIT)||(offl+V19_POST_RF>V19_MAX_WAIT)||(rem<50L)||(rem+V19_TAIL_US*10L>V19_MAX_WAIT)) {\
printf("V19 RF block window infeasible (rf %d)\n", rfn); goto end; }
// Playback of one RF event. Caller has selected matrix/list and set phase.
#define V19_RF_START(mask) starttimer();\
MR3040_Start(mask);\
if (use_pdd>0) userout(pdd_tx_mask);
#define V19_RF_GO(rfn, mul, go, offl) waittimer(go-v19_lead);\
starttimer();\
NEWSHAPE_SETUP(rfn, mul)\
waittimer(v19_unblank);\
rfampon(0);\
if (warmup>10) delay(warmup,us);\
waittimer(v19_lead-V19_ANCHOR);\
rfon(rf_on);\
MR3031_go();\
waittimer(offl);\
rfon(0);\
if (use_pdd>0) userout(pdd_rx_mask);\
waittimer(offl+V19_POST_RF);\
starttimer();
'''


def kappa_check():
    r = json.loads((ROOT / "docs/v19/reference_rf/real_rf_transfer_results.json").read_text())["pulses"]
    m = json.loads((ROOT / "docs/v19/rf_library_manifest.json").read_text())["pulse_frames"]
    for key, (_, frame, dur, tbw, kap, num) in RF.items():
        p = r[frame]
        k = -p["post_RF_correction_cycles_m"] / p["net_RF_gradient_cycles_m"]
        assert abs(round(k * 10000) - kap) <= 1, (frame, k)
        assert m[frame]["rfcal_scale_numerator"] == num, frame

def method_only(t):
    """Remove v18 code the method path cannot reach and size tables for it."""
    for start, end, inclusive in SKIPPED_V18:
        assert t.count(start) == 1 and t.count(end) == 1, start
        i = t.index(start) + (0 if inclusive else len(start))
        j = t.index(end)
        assert i < j
        region = t[i:j]
        assert (len(re.findall(r'(?m)^\s*#if', region)) == len(re.findall(r'(?m)^\s*#endif', region)))
        labels = re.findall(r'(?m)^\s*([A-Za-z_]\w*):(?!=)', region)
        rest = t[:i] + t[j:]
        assert not any(re.search(r'\bgoto\s+' + l + r'\s*;', rest) for l in labels), labels
        t = t[:i] + (KERNEL_JUMP if inclusive else '') + t[j:]
    for name in REJECTED_FEATURES:
        pattern = r'(?m)^#define ' + name + r'\b'
        assert len(re.findall(pattern, t)) == 1, name
        t = re.sub(pattern, r'\\\\#define ' + name, t)
    for old, new in TABLE_DEFINES.items():
        assert t.count(old) == 1, old
        t = t.replace(old, new)
    old = '"%d",1,512,1,1,no_diff_acq;'
    assert t.count(old) == 1
    t = t.replace(old, f'"%d",1,{MAX_DIFF_ACQ},1,1,no_diff_acq;')
    for name in ("acq_b", "acq_grad", "acq_x", "acq_y", "acq_z"):
        pattern = r'(VAR_ARRAY [^\n]*,' + name + r', )512;'
        assert len(re.findall(pattern, t)) == 1, name
        t = re.sub(pattern, r'\g<1>' + str(MAX_DIFF_ACQ) + ';', t)
    return t

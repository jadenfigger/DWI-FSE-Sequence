def _without_comments(text):
    # Only applied to our additions, never to the inherited v18 source.
    # The console cpp expands identifiers inside // comments. PARAMLIST is a
    # vendor block-comment format, so do not run this on the whole PPL either.
    pattern = r'"(?:[^"\\]|\\.)*"|/\*[\s\S]*?\*/|//[^\n]*'
    return re.sub(pattern, lambda m: m[0] if m[0].startswith('"') else
                  '\n' * m[0].count('\n'), text)


def _arguments(text):
    parts, start, depth = [], 0, 0
    for m in re.finditer(r'"(?:[^"\\]|\\.)*"|[(),\[\]]', text):
        token = m[0]
        if token in ('(', '['):
            depth += 1
        elif token in (')', ']'):
            depth -= 1
        elif token == ',' and depth == 0:
            parts.append(text[start:m.start()].strip())
            start = m.end()
    parts.append(text[start:].strip())
    return parts


def _call_end(text, opening):
    depth = 1
    for m in re.finditer(r'"(?:[^"\\]|\\.)*"|[()]', text[opening + 1:]):
        if m[0] == '(':
            depth += 1
        elif m[0] == ')':
            depth -= 1
        if depth == 0:
            return opening + 1 + m.end()
    raise ValueError('Unclosed generated call')


def _helper_definitions():
    # Expand our helper bodies here, rather than in the console's limited cpp
    # argument buffer. Vendor macros remain in their original supported form.
    logical = re.sub(r'\\\n', '\n', _without_comments(MACROS))
    definitions = {}
    for m in re.finditer(r'^#define (V19_\w+)\(([^)]*)\) ([\s\S]*?)(?=^#define |\Z)',
                         logical, re.M):
        definitions[m[1]] = ([p.strip() for p in m[2].split(',')], m[3].rstrip())
    return definitions


PRINTF_LITERAL_LIMIT = 48  # conservative source-character bound, not a vendor specification


def _short_prints(text):
    pattern = r'\bprintf\s*\('
    start = 0
    while (m := re.search(pattern, text[start:])) is not None:
        begin = start + m.start()
        opening = start + m.end() - 1
        end = _call_end(text, opening)
        args = _arguments(text[opening + 1:end - 1])
        literal = args[0]
        assert literal.startswith('"') and literal.endswith('"'), literal
        body = literal[1:-1]
        if len(body) <= PRINTF_LITERAL_LIMIT:
            start = end
            continue
        # Never split an escape or a conversion. Preserve every character and
        # keep each conversion with its own argument; no added runtime newline.
        atoms = re.findall(r'\\.|%(?:[-+ #0]*\d*(?:\.\d+)?[hlL]?[diuoxXfFeEgGcs]|%)|[^\\%]', body)
        assert ''.join(atoms) == body, body
        chunks, current = [], ''
        for atom in atoms:
            if len(current) + len(atom) > PRINTF_LITERAL_LIMIT:
                chunks.append(current)
                current = ''
            current += atom
        if current:
            chunks.append(current)
        calls, index = [], 1
        for chunk in chunks:
            conversions = re.findall(r'%(?:[-+ #0]*\d*(?:\.\d+)?[hlL]?[diuoxXfFeEgGcs]|%)', chunk)
            count = sum(c != '%%' for c in conversions)
            values = args[index:index + count]
            assert len(values) == count
            index += count
            calls.append('printf("' + chunk + '"' + (', ' + ', '.join(values) if values else '') + ')')
        assert index == len(args), (body, args)
        replacement = ';\n'.join(calls)
        text = text[:begin] + replacement + text[end:]
        start = begin + len(replacement)
    return text


ERROR_MESSAGES = {}


def compact_stopping_diagnostics(text):
    """Replace only terminating diagnostic calls, retaining their goto/guards.

    Comments are masked with equal-length spaces so inherited comment examples
    and parameter definitions are never rewritten.
    """
    lexical = r'"(?:[^"\\]|\\[\s\S])*"|/\*[\s\S]*?\*/|//[^\n]*|\\\\[^\n]*'
    masked = re.sub(lexical, lambda m: m[0] if m[0].startswith('"') else
                    ''.join('\n' if c == '\n' else ' ' for c in m[0]), text)
    changes = []
    for match in re.finditer(r'\bprintf\s*\(', masked):
        end = _call_end(text, match.end() - 1)
        if not re.match(r'\s*;\s*goto end\s*;', masked[end:]):
            continue
        args = _arguments(text[match.end():end - 1])
        if args[0].startswith('"Duration='):
            continue
        key = tuple(args)
        if key not in ERROR_MESSAGES:
            ERROR_MESSAGES[key] = len(ERROR_MESSAGES) + 1
        changes.append((match.start(), end, f'v19_error_code={ERROR_MESSAGES[key]}'))
    for begin, end, replacement in reversed(changes):
        text = text[:begin] + replacement + text[end:]
    return text


def compact_v19_errors(text):
    """Share failure reporting; successful paths retain every guard and value."""
    start = 0
    while (match := re.search(r'\bprintf\s*\(', text[start:])) is not None:
        begin = start + match.start()
        opening = start + match.end() - 1
        end = _call_end(text, opening)
        args = _arguments(text[opening + 1:end - 1])
        following = re.match(r'\s*;\s*goto end\s*;', text[end:])
        if following and args[0].startswith('"V19'):
            key = tuple(args)
            if key not in ERROR_MESSAGES:
                ERROR_MESSAGES[key] = len(ERROR_MESSAGES) + 1
            replacement = f'v19_error_code={ERROR_MESSAGES[key]}; goto v19_fail;'
            text = text[:begin] + replacement + text[end + following.end():]
            start = begin + len(replacement)
        else:
            start = end
    return text


def compiler_compatible(insertion):
    text = _without_comments(insertion)
    # No large function-like V19 definitions are emitted to the scanner.
    if insertion == MACROS + MATRIX_DEFS:
        text = _without_comments(MACROS)
        text = re.sub(r'\\\n', '\n', text)
        text = re.sub(r'^#define V19_\w+\([^)]*\) [\s\S]*?(?=^#define |\Z)', '', text, flags=re.M)
        text += _without_comments(MATRIX_DEFS)
    helpers = _helper_definitions()
    pattern = r'\b(' + '|'.join(helpers) + r')\s*\('
    while (m := re.search(pattern, text)) is not None:
        opening = m.end() - 1
        end = _call_end(text, opening)
        values = _arguments(text[opening + 1:end - 1])
        names, body = helpers[m[1]]
        assert len(names) == len(values), m[1]
        replacements = dict(zip(names, values))
        expanded = re.sub(r'"(?:[^"\\]|\\.)*"|\b[A-Za-z_]\w*\b',
                          lambda token: replacements.get(token[0], token[0]), body)
        text = text[:m.start()] + expanded + text[end:]
    if insertion.startswith(SETUP_COMMON_A):
        text = reduce_setup_conversions(text)
    return _short_prints(compact_v19_errors(text))


def reduce_setup_conversions(text):
    """Remove conversion calls only in untimed setup, preserving expression width.

    Every replacement first evaluates the parenthesized argument as signed int,
    then promotes that result with a long zero. No neighboring expression is
    used to infer promotion, so precedence and left-associative sums are safe.
    """
    long_names = {'templ1', 'templ2', 'templ3', 'templ4', 'templ5', 'tr_min',
                  'sm_delta_us', 'big_delta_us', 'tacq', 'tacq_2'}
    int_names = {'tramp', 'rfdelay', 'warmup', 'rfgate_delay', 'te', 'esp',
                 'no_samples', 'no_discard', 'sample_period', 'crusher_max_dac',
                 'crusher_saved_train', 'crusher_saved_first',
                 'crusher_slew_dac_100us', 'tdp', 'tcrush', 'diff_tcrush',
                 'rf_length', 'temp', 'tfilter', 'views_per_seg'}
    for typ, declaration in re.findall(r'\b(int|long) ([^;]+);', DECL_COMMON + DECL_SSMGOT):
        names = {re.match(r'\w+', v.strip())[0] for v in declaration.split(',')}
        (long_names if typ == 'long' else int_names).update(names)
    for match in reversed(list(re.finditer(r'\bIntToLong\(', text))):
        end = _call_end(text, match.end() - 1)
        argument = text[match.end():end - 1]
        # These setup arguments contain only int names, in-range constants and
        # ordinary arithmetic/indexing. Refuse an unknown or long expression.
        words = set(re.findall(r'[A-Za-z_]\w*', argument))
        literals = re.findall(r'\b\d+\b', argument)
        if (not words <= int_names or
                any(int(n) > 32767 for n in literals) or
                not re.fullmatch(r'[\w\s+*/%()\[\]-]+', argument)):
            raise ValueError('unverified int conversion argument: ' + argument)
        assignment = re.search(r'\b(' + '|'.join(sorted(long_names)) + r')\s*=\s*$', text[:match.start()])
        if argument.isdigit():
            replacement = argument + 'L'
        elif assignment and re.match(r'\s*;', text[end:]):
            replacement = '(' + argument + ')'
        else:
            replacement = '(0L+(' + argument + '))'
        text = text[:match.start()] + replacement + text[end:]
    return text


STOP_HUB_ANCHOR = '\tv19_error_code=0;\n'
STOP_HUB = '\tgoto v19_run;\nv19_fail:\nend:\n\tgoto v19_exit;\nv19_run:\n'
EXIT_LABELS = '\nv19_fail:\nend:\n'


def backward_stop_hub(text):
    """Define the terminating labels before any jump to them.

    PPLC E106 (far scratch space overflow) was raised at the 147th forward
    goto in every failing v19 build, whatever the string, token or conversion
    counts; v18 compiles with 145. Unresolved forward label references are the
    exhausted resource. `end`/`v19_fail` now label a hub after the first
    statement, so every later jump to them, including those expanded from
    vendor macros and includes, resolves immediately. The hub's one forward
    jump reaches the unchanged shared exit at the old label position.
    """
    assert text.count(STOP_HUB_ANCHOR) == 1 and text.count(EXIT_LABELS) == 1
    assert not re.search(r'\bv19_(run|exit)\b', text)
    text = text.replace(EXIT_LABELS, '\nv19_exit:\n')
    hub = text.index(STOP_HUB_ANCHOR) + len(STOP_HUB_ANCHOR)
    assert not re.search(r'\bgoto\b', _without_comments(text[:hub]))
    return text[:hub] + STOP_HUB + text[hub:]



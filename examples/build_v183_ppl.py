"""Reproduce v1.83 from the v1.82 bytes that were run on the scanner on 2026-10-11.

v1.83 changes only the off-centre (multi-slice) RF phase handling, via two
console parameters:

* ``v183_phmode`` 0 (default): the vendor scheme of the original FSE (v1.0) and
  v1.81. The transmit buffer stays at the slice frequency and every refocusing
  pulse and receiver phase gets the per-echo ``phase_ang`` increment, including
  the console-calibrated ``phcor_plus``/``phcor_minus``. On 2026-10-10 v1.81
  showed no per-echo phase ramp in off-centre slices with this scheme.
* ``v183_phmode`` 1: v1.82's gated scheme (offset carrier only around each RF,
  explicit phase bookkeeping), with ``v183_phcal`` ticks (0.1 us) added to the
  modelled per-RF window:
  ``v182_step = slice_freq_long*(tsel90*10+1800+v183_phcal) mod 10^7``.
  Mode 1 with v183_phcal 0 plays exactly what v1.82 plays.

Why: on 2026-10-11 every off-centre v1.82 slice showed a steady echo-phase ramp
of about 41 degrees per echo per mm of console z (K at +/-1.2 mm, S and V at
+/-2.4 mm; docs/physical_scanner_experiments_2026-10-11.md section 3). A
refocusing-phase error that grows by theta per pulse appears as an echo-phase
ramp of theta per echo. At the 2130 Hz/mm slice frequency of rfnum 1 (3 kHz sinc
at 71%) the ramp equals about 53 us of offset phase per pulse that v1.82's model
omits, so |v183_phcal| of about 530 is the mode-1 starting point. Both modes and
the sign are to be decided on the scanner (docs/v183/CALIBRATION.md).
"""
from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "scanner/FSE_dwi_CPMG_non_CPMG_twoTE-1.82.ppl"
BASE_PPR = BASE.with_suffix(".ppr")
PPL = ROOT / "scanner/FSE_dwi_CPMG_non_CPMG_twoTE-1.83.ppl"
PPR = PPL.with_suffix(".ppr")
BASE_SHA256 = "93a91c61e02b567d6440ce0709a9b7e45663be4d267e80defd715b382396095f"
BASE_PPR_SHA256 = "44474269a39ebaa8efed9526000413dd4f8372082f520e890e005ffa8fd4f84b"


def generate_ppl() -> str:
    raw = BASE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != BASE_SHA256:
        raise RuntimeError("v1.82 source changed; review the transformation")
    s = raw.decode("latin-1").replace("\r\n", "\n")

    def replace(old: str, new: str, count: int = 1) -> None:
        nonlocal s
        if s.count(old) != count:
            raise RuntimeError(f"Expected {count} anchors: {old[:100]!r}")
        s = s.replace(old, new)

    replace("v1.82 candidate, 11 October 2026; source model only.", """v1.83 candidate, 12 October 2026; source model only.
Generated by examples/build_v183_ppl.py from v1.82 (scanned 11 Oct).
Off-centre RF phase is selectable. v183_phmode 0 (default) = vendor
per-echo phase_ang scheme of v1.0/v1.81 (phcor_plus/minus apply).
v183_phmode 1 = v1.82 gated carrier; v183_phcal (0.1 us per RF) is
added to its modelled offset window. Mode 1 with phcal 0 = v1.82.
Calibrate with three-slice scans; see docs/v183/CALIBRATION.md.

v1.82 candidate, 11 October 2026; source model only.""")
    replace('EDITTEXT  "Read frequency phase correction", "", "%d", -32768,32767,0,1, r_phcor;',
            'EDITTEXT  "Read frequency phase correction", "", "%d", -32768,32767,0,1, r_phcor;\n'
            'SCROLLBAR "Off-centre RF phase mode","0=vendor/v1.81 1=v1.82 gated","%d",0,1,0,1,v183_phmode;\n'
            'EDITTEXT  "Off-centre RF phase cal","0.1 us per RF pulse (mode 1)","%d",-2000,2000,0,1,v183_phcal;')
    replace("\tint v182_rfp;", "\tint v182_rfp, v183_phmode, v183_phcal;")
    replace("\tlong v182_pacc, v182_step, v182_lead;", "\tlong v182_pacc, v182_step, v182_lead, v183_f;")
    # Mode 0: keep the slice frequency for the vendor per-echo term, then zero
    # slice_freq_long. Transmit buffer 0 has already been given the offset
    # carrier (fov_slice_freq, kHz_new), and every later use of slice_freq_long
    # is a v1.82 gated branch or v182_step, so mode 0 plays v1.82's own
    # centred-slice code plus the vendor phase increments. v1.82's timed code
    # is not edited, so mode 1 keeps v1.82's played events exactly.
    replace("\tslice_freq_var = 0;\n", """\tslice_freq_var = 0;
\tv183_f=0L;
\tif (v183_phmode==0)
\t{
\t\tv183_f=slice_freq_long;
\t\tslice_freq_long=0L;
\t}
""")
    # Restore the inherited per-echo slice term (v1.0/v1.81 NEWPHCOR) in mode 0;
    # v183_f is 0 in mode 1, as v1.82's templ1. slice_freq_var is already zero
    # here, as it was in v1.81.
    replace("\ttempl1 = 0L;\n\ttempl2 = - read_freq_long - IntToLong(rec_freq);",
            "\ttempl1 = v183_f;\n\ttempl2 = - read_freq_long - IntToLong(rec_freq);")
    # Overflow guard for the longest window allowed (v183_phcal <= +2000 ticks),
    # kept as a constant so it costs no image bytes.
    replace("\t\ttempl1=2147483647L/(IntToLong(tsel90)*10L+1800L);",
            "\t\ttempl1=2147483647L/(IntToLong(tsel90)*10L+3800L);")
    replace("\tv182_step=(slice_freq_long*(IntToLong(tsel90)*10L+1800L))%10000000L;",
            "\tv182_step=(slice_freq_long*(IntToLong(tsel90)*10L+1800L+IntToLong(v183_phcal)))%10000000L;")
    # Console compiler: "branch is out of range". v1.81 routes every error to an
    # early 'end:' whose 'goto v181_exit' jumps forward over the whole program;
    # v1.82 was just inside the range and v1.83's additions pushed it over.
    # Relay that jump through a label in once-only setup code before the gating
    # and experiment loops, which roughly halves it. Normal flow skips the relay
    # with one untimed goto. A shorter error string pays for the two gotos.
    replace("end:\n\tgoto v181_exit;\nv181_run:", "end:\n\tgoto v183_relay;\nv181_run:")
    replace("\n#ifdef AUTOGATE\n/**************** AUTOMATIC GATE DETECTION CODE",
            "\n\tgoto v183_skip;\nv183_relay:\n\tgoto v181_exit;\nv183_skip:\n\n#ifdef AUTOGATE\n/**************** AUTOMATIC GATE DETECTION CODE")
    replace('printf("V182 raw views: >=2 shots of ETL+1\\n")', 'printf("V182 raw views\\n")')
    # Console compiler, .fth line 4173: the second crush_independent_on IF
    # (crusher schedule setup) is byte-identical to v1.8's but sits at the
    # IF branch limit; a small address shift (inline-string alignment) put it
    # over. Coded messages free ~280 bytes inside that IF body.
    for i, text in enumerate((
            "Crusher amplitude/slew ceilings must be positive",
            "Custom crusher count must equal ETL and be 1..64",
            "Custom crusher storage contains invalid percentage",
            "Crusher progression overflow",
            "Invalid custom crusher percentage",
            "Crusher magnitude product overflow",
            "Crusher amplitude exceeds DAC/gradient ceiling",
            "Crusher ramp exceeds slew ceiling"), start=1):
        replace(f'printf("{text}\\n")', f'printf("Crusher E{i}\\n")')
    # The error persisted at the same THEN, so the IF branch itself is the
    # limit (as in v1.9's fifth trial, docs/v19/README.md): skip the block with
    # a goto, which the compiler resolves over far longer spans. The body is
    # unchanged; only its enclosing if/braces become goto + label.
    replace("\tif (crush_independent_on==1)\n\t{\n\t\tif ((crusher_max_dac<1)",
            "\tif (crush_independent_on!=1) goto v183_cs_done;\n\t\tif ((crusher_max_dac<1)")
    replace("\t\tif (crusher_i<crusher_etl) goto crusher_schedule_loop;\n\t}\n\ttcrush_play = tcrush+crush_pre_pad;",
            "\t\tif (crusher_i<crusher_etl) goto crusher_schedule_loop;\nv183_cs_done:\n\ttcrush_play = tcrush+crush_pre_pad;")
    return s


def generate_ppr() -> str:
    raw = BASE_PPR.read_bytes()
    if hashlib.sha256(raw).hexdigest() != BASE_PPR_SHA256:
        raise RuntimeError("v1.82 protocol changed; review provenance")
    s = raw.decode("latin-1").replace("\r\n", "\n")
    if s.count(BASE.name) != 1 or s.count(":VAR r_phcor, 0\n") != 1:
        raise RuntimeError("v1.82 PPR anchors changed")
    s = s.replace(BASE.name, PPL.name)
    return s.replace(":VAR r_phcor, 0\n", ":VAR r_phcor, 0\n:VAR v183_phmode, 0\n:VAR v183_phcal, 0\n")


def build() -> dict[str, str]:
    result = {}
    for path, text in ((PPL, generate_ppl()), (PPR, generate_ppr())):
        data = text.replace("\n", "\r\n").encode("latin-1")
        path.write_bytes(data)
        result[str(path.relative_to(ROOT))] = hashlib.sha256(data).hexdigest()
    return result


if __name__ == "__main__":
    for path, digest in build().items():
        print(digest, path)

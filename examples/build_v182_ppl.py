ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "scanner/FSE_dwi_CPMG_non_CPMG_twoTE-1.81.ppl"
BASE_PPR = BASE.with_suffix(".ppr")
PPL = ROOT / "scanner/FSE_dwi_CPMG_non_CPMG_twoTE-1.82.ppl"

def generate_ppr() -> str:
    raw=BASE_PPR.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=BASE_PPR_SHA256:
        raise RuntimeError("v1.81 protocol changed; review provenance")
    s = raw.decode("latin-1").replace("\r\n", "\n")
    return s.replace(BASE.name, PPL.name)


def build() -> dict[str, str]:
    result = {}
    for path, text in ((PPL, generate_ppl()), (PPR, generate_ppr())):
        data = text.replace("\n", "\r\n").encode("latin-1")
        path.write_bytes(data)
        result[str(path.relative_to(ROOT))] = hashlib.sha256(data).hexdigest()
    return result


if __name__ == "__main__":
    for path, digest in build().items():
        print(digest, path)
